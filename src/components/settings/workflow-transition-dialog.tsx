"use client";

import * as React from "react";
import { ArrowRight, Archive } from "lucide-react";
import { firstFieldErrors, useMutationRunner } from "@/components/jobs/mutation";
import { StatusPill } from "@/components/jobs/status-pill";
import { Button } from "@/components/ui/button";
import { Checkbox } from "@/components/ui/checkbox";
import { Dialog, DialogBody, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { FormField } from "@/components/ui/form-field";
import { Input } from "@/components/ui/input";
import { Select } from "@/components/ui/select";
import { api } from "@/lib/api-client";
import { ROLES, ROLE_LABELS, type Role } from "@/lib/constants";
import type { WorkflowStatusView, WorkflowTransitionView } from "@/lib/types";

export interface TransitionDraft {
  fromStatusId: string;
  toStatusId: string;
}

export interface TransitionDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  workflowId: string;
  statuses: WorkflowStatusView[];
  /** Existing stored edge, a generated edge (to store explicitly), or a draft pair. */
  transition: WorkflowTransitionView | null;
  draft: TransitionDraft | null;
  readOnly: boolean;
}

const FLAG_HELP = {
  assigneeOnly: "Editors may only take this edge on jobs assigned to them.",
  requiresAssignedEditor: "Blocked unless the job has an active editor.",
  isReopen: "Counts as reopening a finished job (requires a reason; increments reopen count).",
} as const;

/** Add / edit / archive one transition (edge) of a workflow. */
export function TransitionDialog({ open, onOpenChange, workflowId, statuses, transition, draft, readOnly }: TransitionDialogProps) {
  const run = useMutationRunner();
  const stored = transition !== null && !transition.generated;
  const live = statuses.filter((s) => s.archivedAt === null);
  const [from, setFrom] = React.useState(transition?.fromStatusId ?? draft?.fromStatusId ?? live[0]?.id ?? "");
  const [to, setTo] = React.useState(transition?.toStatusId ?? draft?.toStatusId ?? live[1]?.id ?? "");
  const [label, setLabel] = React.useState(transition?.label ?? "");
  const [roles, setRoles] = React.useState<Role[]>(transition?.allowedRoles ?? ["owner", "manager"]);
  const [assigneeOnly, setAssigneeOnly] = React.useState(transition?.assigneeOnly ?? false);
  const [requiresEditor, setRequiresEditor] = React.useState(transition?.requiresAssignedEditor ?? false);
  const [isReopen, setIsReopen] = React.useState(transition?.isReopen ?? false);
  const [errors, setErrors] = React.useState<Record<string, string>>({});
  const [pending, setPending] = React.useState<"save" | "archive" | null>(null);

  const byId = new Map(statuses.map((s) => [s.id, s]));
  const fromStatus = byId.get(from);
  const toStatus = byId.get(to);
  const fixedPair = transition !== null || draft !== null;

  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (readOnly) return;
    setErrors({});
    if (roles.length === 0) {
      setErrors({ allowedRoles: "Choose at least one role" });
      return;
    }
    setPending("save");
    const flags = { label: label.trim() || null, allowedRoles: roles, assigneeOnly, requiresAssignedEditor: requiresEditor, isReopen };
    const res = stored
      ? await run(() => api.patch(`/api/transitions/${transition.id}`, flags), { success: "Transition updated" })
      : await run(() => api.post(`/api/workflows/${workflowId}/transitions`, { fromStatusId: from, toStatusId: to, ...flags }), { success: "Transition added" });
    setPending(null);
    if (res.ok) onOpenChange(false);
    else if (res.fieldErrors) setErrors(firstFieldErrors(res.fieldErrors));
  };

  const archive = async () => {
    if (!stored) return;
    setPending("archive");
    const res = await run(() => api.post(`/api/transitions/${transition.id}/archive`, {}), { success: "Transition removed", successDescription: "Kept in history; jobs can no longer take it." });
    setPending(null);
    if (res.ok) onOpenChange(false);
  };

  const title = readOnly ? "Transition" : stored ? "Edit transition" : transition?.generated ? "Customise cancel transition" : "Add a transition";

  return (
    <Dialog open={open} onOpenChange={(o) => (pending ? undefined : onOpenChange(o))} size="md">
      <form onSubmit={submit} noValidate className="flex min-h-0 flex-1 flex-col">
        <DialogHeader>
          <DialogTitle>{title}</DialogTitle>
          <DialogDescription>
            {transition?.generated
              ? "Generated by the engine so every active status can be cancelled. Store it explicitly to change who may cancel."
              : "Who may move a job from one status to another, and under which conditions."}
          </DialogDescription>
        </DialogHeader>
        <DialogBody className="flex flex-col gap-4 pb-4">
          {fixedPair ? (
            <div className="flex flex-wrap items-center gap-2 rounded-md bg-surface-sunken px-3 py-2.5">
              {fromStatus ? <StatusPill status={fromStatus} /> : null}
              <ArrowRight aria-hidden="true" className="size-4 text-ink-subtle" />
              {toStatus ? <StatusPill status={toStatus} /> : null}
            </div>
          ) : (
            <div className="grid gap-4 sm:grid-cols-2">
              <FormField label="From" error={errors.fromStatusId}>
                <Select value={from} onChange={(e) => setFrom(e.target.value)}>
                  {live.map((s) => (
                    <option key={s.id} value={s.id}>
                      {s.name}
                    </option>
                  ))}
                </Select>
              </FormField>
              <FormField label="To" error={errors.toStatusId}>
                <Select value={to} onChange={(e) => setTo(e.target.value)}>
                  {live.map((s) => (
                    <option key={s.id} value={s.id} disabled={s.id === from}>
                      {s.name}
                    </option>
                  ))}
                </Select>
              </FormField>
            </div>
          )}
          <FormField label="Button label" optional description="Shown on the job's action button, e.g. “Submit for review”." error={errors.label}>
            <Input value={label} onChange={(e) => setLabel(e.target.value)} disabled={readOnly} maxLength={80} placeholder={toStatus ? `Move to ${toStatus.name}` : ""} />
          </FormField>
          <fieldset>
            <legend className="mb-2 text-sm font-medium text-ink">Allowed roles</legend>
            <div className="flex flex-wrap gap-2">
              {ROLES.map((r) => (
                <Checkbox
                  key={r}
                  checked={roles.includes(r)}
                  onChange={(e) => setRoles((cur) => (e.target.checked ? [...cur, r] : cur.filter((x) => x !== r)))}
                  disabled={readOnly}
                  label={ROLE_LABELS[r]}
                  wrapperClassName="rounded-md border border-border px-3 py-2"
                />
              ))}
            </div>
            <p className="mt-1.5 text-xs text-ink-muted">Photographers only ever act on their own jobs.</p>
            {errors.allowedRoles ? <p className="mt-1 text-sm text-danger">{errors.allowedRoles}</p> : null}
          </fieldset>
          <fieldset className="flex flex-col gap-3">
            <legend className="mb-2 text-sm font-medium text-ink">Conditions</legend>
            <Checkbox checked={assigneeOnly} onChange={(e) => setAssigneeOnly(e.target.checked)} disabled={readOnly} label="Assigned editor only" description={FLAG_HELP.assigneeOnly} />
            <Checkbox
              checked={requiresEditor}
              onChange={(e) => setRequiresEditor(e.target.checked)}
              disabled={readOnly}
              label="Requires an assigned editor"
              description={FLAG_HELP.requiresAssignedEditor}
            />
            <Checkbox checked={isReopen} onChange={(e) => setIsReopen(e.target.checked)} disabled={readOnly} label="Reopen" description={FLAG_HELP.isReopen} />
          </fieldset>
        </DialogBody>
        <DialogFooter className="sm:justify-between">
          {stored && !readOnly ? (
            <Button variant="ghost" className="text-danger hover:bg-danger-soft" leadingIcon={<Archive aria-hidden="true" />} onClick={archive} loading={pending === "archive"} disabled={pending !== null}>
              Remove
            </Button>
          ) : (
            <span />
          )}
          <div className="flex flex-col-reverse gap-2 sm:flex-row">
            <Button variant="ghost" onClick={() => onOpenChange(false)} disabled={pending !== null}>
              {readOnly ? "Close" : "Cancel"}
            </Button>
            {!readOnly ? (
              <Button type="submit" loading={pending === "save"} disabled={pending !== null}>
                {stored ? "Save transition" : "Add transition"}
              </Button>
            ) : null}
          </div>
        </DialogFooter>
      </form>
    </Dialog>
  );
}
